// Кризисный фильтр. Срабатывает ДО модели: при остром риске ответ не генерируется, бот сразу даёт 112 и линию МЧС.
// Ложное срабатывание дешевле пропуска, поэтому фразы широкие, а отрицания не разбираем.
//
// Два уровня:
//   acute    мысли о смерти, самоповреждение, насилие: заготовленный текст, модель не вызываем.
//   distress паника, «мне очень плохо», «нет сил»: модель отвечает, бот добавляет контакты помощи.

const ACUTE = [
  /суицид/,
  /покончи(ть|ла?) с собой/,
  /(убить|убью|убиваю) себя/,
  /не\s+хочу\s+(больше\s+)?жить/,
  /(хочу|хочется|хотела?)\s+умереть/,
  /жить\s+не\s+хочется/,
  /(лучше\s+бы\s+меня\s+не\s+было|без\s+меня\s+(всем\s+)?будет\s+лучше)/,
  /самоповрежд/,
  /(порезать|режу|резать|порезала?)\s+(себя|себе|вены|руки)/,
  /вскрыть\s+вены/,
  /(выпилиться|роскомнадзорнуться)/,
  /(наглотаться|наглоталась?)\s+таблет/,
  /(спрыгнуть|прыгнуть|сброситься)\s+(с|из)\s/,
  /(повеситься|повешусь)/,
  /(меня\s+(бьют|избивают|насилуют|изнасиловали?)|он\s+меня\s+(бьёт|бьет|душит))/,
  /(хочу|собираюсь)\s+(убить|прибить)\s/,
];

const DISTRESS = [
  /мне\s+(очень\s+|так\s+|совсем\s+|сейчас\s+|реально\s+)?(плохо|хреново|херово|тяжело|страшно)/,
  /плохо\s+мне/,
  /не\s+могу\s+больше/,
  /нет\s+сил/,
  /пани[кч]/,
  /задыхаюсь/,
  /помогите/,
  /помоги\s+мне/,
  /хочу\s+исчезнуть/,
];

function normalize(text) {
  return ` ${String(text).toLowerCase().replace(/ё/g, 'е').replace(/\s+/g, ' ')} `;
}

const norm = (list) => list.map((r) => new RegExp(r.source.replace(/ё/g, 'е'), 'u'));
const ACUTE_N = norm(ACUTE);
const DISTRESS_N = norm(DISTRESS);

/** @returns {'acute' | 'distress' | null} */
export function detectCrisis(text) {
  const t = normalize(text);
  if (ACUTE_N.some((r) => r.test(t))) return 'acute';
  if (DISTRESS_N.some((r) => r.test(t))) return 'distress';
  return null;
}
